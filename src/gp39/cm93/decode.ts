/** octet du fichier → octet réel */
export const DECODE_TABLE: Uint8Array = (() => {
  const t = new Uint8Array(256)
  for (let i = 0; i < 256; i++) t[TABLE_0[i]! ^ 8] = i
  return t
})()

/** Décode un tampon brouillé (copie : le tampon d'origine n'est pas modifié). */
export function descramble(src: Uint8Array): Uint8Array<ArrayBuffer> {
  const out = new Uint8Array(src.length)
  for (let i = 0; i < src.length; i++) out[i] = DECODE_TABLE[src[i]!]!
  return out
}
